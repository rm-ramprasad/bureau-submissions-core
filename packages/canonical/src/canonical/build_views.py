"""Generate the Postgres and MySQL copies of the source views from the one T-SQL source (user decision, 2026-11-02:
fixed, reviewed per-dialect scripts, made at build time; never translated at runtime).

    uv run python -m canonical.build_views            # write migrations/<dialect>/views/
    uv run python -m canonical.build_views --check    # fail if the committed files differ (the tests check too)

Source: migrations/azure/views/ (T-SQL, run on Azure SQL / SQL Server as it is). For each other dialect:
  - 00_functions.sql is copied from migrations/views-overrides/<dialect>/ (hand-written: functions do not translate);
  - every other file is translated by SQLGlot (pinned in pyproject.toml, so the same source gives the same SQL), batch
    by batch (GO), failing on anything SQLGlot cannot translate.
The source must stay in the portable subset; the forms SQLGlot translates wrongly are refused here (see FORBIDDEN).
"""

from __future__ import annotations

import argparse
import re
import sys
from importlib.metadata import version
from pathlib import Path

ROOT = Path(__file__).resolve().parent / "migrations"
SOURCE = ROOT / "azure" / "views"
OVERRIDES = ROOT / "views-overrides"
DIALECTS = {"postgres": "postgres", "mysql": "mysql"}  # output folder -> SQLGlot dialect
FUNCTIONS_FILE = "00_functions.sql"
SQLGLOT_VERSION = "26.16.0"

# Forms that translate to wrong SQL without an error (feasibility check, 2026-11-02), and what to write instead.
FORBIDDEN = [
    (re.compile(r"'[^'\n]*'\s*\+|\+\s*'"), "string '+' concatenation (MySQL adds numbers: '0' + '5' = 5): use CONCAT"),
    (
        re.compile(r"\bTRY_CAST\b|\bTRY_CONVERT\b", re.I),
        "TRY_CAST / TRY_CONVERT (become CAST: MySQL gives 0 for a bad cell): use automn.fn_amount / fn_percent / fn_int",
    ),
    (re.compile(r"\bfn_(label|code)_value\b", re.I), "label / code functions: join automn.vw_ref_label / vw_ref_code"),
    (re.compile(r"\bCREATE\s+(OR\s+ALTER\s+)?FUNCTION\b", re.I), "functions belong in 00_functions.sql (overrides)"),
    (
        re.compile(r"\bOUTER\s+APPLY\b", re.I),
        "OUTER APPLY (becomes LEFT JOIN LATERAL without ON, which Postgres refuses): use CROSS APPLY or a LEFT JOIN",
    ),
]

# SQLGlot writes T-SQL CROSS APPLY as INNER JOIN LATERAL with no ON, which Postgres refuses (found by the Database CI
# job, 2026-11-05). CROSS JOIN LATERAL is the same join and runs on Postgres and MySQL 8.
INNER_LATERAL = re.compile(r"\bINNER JOIN LATERAL\b")


def _strip_comments(sql: str) -> str:
    return re.sub(r"--[^\n]*", "", sql)


def _batches(sql: str) -> list[str]:
    parts = [b.strip() for b in re.split(r"^\s*GO\s*$", sql, flags=re.M)]
    return [b for b in parts if _strip_comments(b).strip()]


def check_source(name: str, sql: str) -> list[str]:
    problems = []
    for lineno, line in enumerate(sql.splitlines(), 1):
        code = _strip_comments(line)
        for pattern, why in FORBIDDEN:
            if pattern.search(code):
                problems.append(f"{name}:{lineno}: {why}")
    return problems


XACT_ABORT = re.compile(r"^\s*SET\s+XACT_ABORT\s+ON\s*;?\s*$", re.I | re.M)


def translate(name: str, sql: str, dialect: str) -> str:
    import sqlglot
    from sqlglot.errors import ErrorLevel

    out = []
    if XACT_ABORT.search(sql):  # T-SQL only. Postgres aborts a transaction on any error anyway; MySQL has none
        sql = XACT_ABORT.sub("-- (SET XACT_ABORT ON: T-SQL only, left out)", sql)
    for batch in _batches(sql):
        # the batch's leading comment lines are kept as they are (SQLGlot would fold them into the statement)
        lines = batch.splitlines()
        lead = next((i for i, ln in enumerate(lines) if not ln.lstrip().startswith("--")), len(lines))
        comment = "\n".join(lines[:lead])
        statements = sqlglot.transpile(
            _strip_comments(batch),
            read="tsql",
            write=DIALECTS[dialect],
            pretty=True,
            unsupported_level=ErrorLevel.RAISE,
        )
        statements = [INNER_LATERAL.sub("CROSS JOIN LATERAL", st) for st in statements]
        out.append((comment + "\n" if comment else "") + ";\n".join(statements) + ";\n")
    return "\n".join(out)


def header(dialect: str, source: str) -> str:
    return (
        f"-- GENERATED by canonical/build_views.py from migrations/azure/views/{source} (sqlglot {SQLGLOT_VERSION},"
        f" {dialect}).\n-- Do not edit: change the T-SQL source and run  python -m canonical.build_views\n\n"
    )


def build() -> dict[Path, str]:
    """Every generated file and its content."""
    installed = version("sqlglot")
    if installed != SQLGLOT_VERSION:
        raise SystemExit(
            f"sqlglot {installed} installed, the build pins {SQLGLOT_VERSION}: uv sync (the dev group pins it)"
        )
    sources = sorted(SOURCE.glob("*.sql"))
    problems = [
        p for s in sources if s.name != FUNCTIONS_FILE for p in check_source(s.name, s.read_text(encoding="utf-8"))
    ]
    if problems:
        raise SystemExit("Not in the portable subset:\n  " + "\n  ".join(problems))
    files = {}
    for dialect in DIALECTS:
        target = ROOT / dialect / "views"
        override = OVERRIDES / dialect / FUNCTIONS_FILE
        if not override.is_file():
            raise SystemExit(f"missing {override.relative_to(ROOT)}: the {dialect} functions are hand-written")
        files[target / FUNCTIONS_FILE] = override.read_text(encoding="utf-8")
        for s in sources:
            if s.name != FUNCTIONS_FILE:
                files[target / s.name] = header(dialect, s.name) + translate(
                    s.name, s.read_text(encoding="utf-8"), dialect
                )
    return files


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--check", action="store_true", help="compare with the committed files; write nothing")
    args = p.parse_args()
    files = build()
    stale = []
    for path, content in files.items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != content:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")
    for path in stale:
        print(("STALE " if args.check else "wrote ") + str(path.relative_to(ROOT)))
    if args.check and stale:
        print("Run  uv run python -m canonical.build_views  and commit the result.")
        return 1
    print(f"{len(files)} files, {len(stale)} {'stale' if args.check else 'changed'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
